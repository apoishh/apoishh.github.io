"""
Refreshes the YouTube page: your latest upload + your 4 most-viewed videos.

    python update_videos.py

Reads the channel set as youtubeChannel in js/config.js and writes js/videos.js.
The daily GitHub job runs this for you.
Needs:  pip install yt-dlp
"""
from pathlib import Path
import json
import re
import time

ROOT = Path(__file__).parent
CONFIG = ROOT / "js" / "config.js"
OUT_JS = ROOT / "js" / "videos.js"
TOP_N = 4


def channel_url():
    m = re.search(r'youtubeChannel:\s*"([^"]+)"', CONFIG.read_text(encoding="utf-8"))
    if not m:
        raise SystemExit("No youtubeChannel set in js/config.js")
    return m.group(1).rstrip("/") + "/videos"


def update():
    import yt_dlp
    opts = {"extract_flat": "in_playlist", "quiet": True, "no_warnings": True}
    with yt_dlp.YoutubeDL(opts) as ydl:
        info = ydl.extract_info(channel_url(), download=False)
    videos = [
        {"id": e["id"], "title": e.get("title") or "", "views": e.get("view_count") or 0}
        for e in info.get("entries") or [] if e and e.get("id")
    ]
    if not videos:
        print("No videos found - keeping the old list.")
        return
    latest = videos[0]  # the /videos tab lists newest first
    popular = sorted((v for v in videos if v["id"] != latest["id"]),
                     key=lambda v: v["views"], reverse=True)[:TOP_N]
    OUT_JS.write_text(
        "// Generated by update_videos.py - don't edit by hand.\n"
        "const VIDEOS = " + json.dumps({"latest": latest, "popular": popular},
                                       indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(time.strftime("[%H:%M:%S]"), f"videos updated: latest '{latest['title']}', "
          f"top {len(popular)} by views")


if __name__ == "__main__":
    update()
